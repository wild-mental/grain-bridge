/** 295 -> "2억 9,500만" (input in millions). */
function koMillions(millions: number): string {
  const man = Math.round(millions * 100); // 1 million = 100만
  const eok = Math.floor(man / 10000);
  const rest = man % 10000;
  if (eok === 0) return `${rest.toLocaleString('ko-KR')}만`;
  return rest === 0 ? `${eok}억` : `${eok}억 ${rest.toLocaleString('ko-KR')}만`;
}

